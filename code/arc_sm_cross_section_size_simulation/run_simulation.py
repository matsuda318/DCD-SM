def score_averages(history: np.ndarray) -> list[np.ndarray]:
    """HAR averages with zero presample scores and exact 1/5/22 denominators."""
    return [
        history[-window:].sum(axis=0) / window
        for window in core.WINDOWS
    ]


def prepare_component_sampler(
    knots: np.ndarray, masses: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    grid = np.linspace(0.0, 1.0, GRID_SIZE)
    basis = core.normalized_bspline_basis(grid, knots, core.DEGREE, masses)
    cdfs = np.cumsum((basis[1:] + basis[:-1]) * 0.5, axis=0)
    cdfs = np.vstack((np.zeros((1, basis.shape[1])), cdfs))
    cdfs /= GRID_SIZE - 1
    cdfs /= cdfs[-1]
    probabilities = np.linspace(0.0, 1.0, GRID_SIZE)
    inverse = np.column_stack([
        np.interp(probabilities, cdfs[:, j], grid)
        for j in range(len(masses))
    ])
    return grid, basis, cdfs, inverse


def sample_u(
    count: int,
    q_state: np.ndarray,
    masses: np.ndarray,
    helmert: np.ndarray,
    component_inverse: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    logits = np.log(masses) + helmert @ q_state
    weights = np.exp(logits - logsumexp(logits))
    components = rng.choice(len(masses), size=count, p=weights)
    probabilities = np.linspace(0.0, 1.0, len(component_inverse))
    uniforms = rng.random(count)
    output = np.empty(count)
    for component in np.unique(components):
        selected = components == component
        output[selected] = np.interp(
            uniforms[selected], probabilities, component_inverse[:, component]
        )
    return np.clip(output, 1e-12, 1.0 - 1e-12)


def calibration() -> dict[str, object]:
    saved = json.loads(CALIBRATION.read_text(encoding="utf-8"))
    anchor = np.asarray(saved["model1"]["state"], dtype=float)
    # Standardize location/scale without changing the skew-t shape anchor.
    anchor[:2] = (0.0, 0.0)
    # The empirical coefficients were estimated from roughly 500 daily
    # constituents.  The sqrt adjustment preserves approximately the same
    # innovation scale when the DGP driver contains 100 observations.
    empirical_n = 491.0
    adjustment = math.sqrt(MASTER_N / empirical_n)
    m2 = np.asarray(saved["model2_betas"], dtype=float)
    eta = np.asarray(saved["model3_betas"], dtype=float)[:, 0]
    endpoint_even = np.asarray(saved["model4"]["coefficients"], dtype=float)[0]
    return {
        "anchor": anchor,
        "adjustment": adjustment,
        "empirical_cross_section_for_adjustment": empirical_n,
        "scale_kappa": m2[:, 1] * adjustment,
        "eta_kappa": eta * adjustment,
        "even_kappa": endpoint_even * adjustment,
    }


def generate_master_panel(
    dgp: str,
    rng: np.random.Generator,
    calibrated: dict[str, object],
    knots: np.ndarray,
    masses: np.ndarray,
    helmert: np.ndarray,
    directions: np.ndarray,
    shape_geometry: shape.ShapeGeometry,
    q_projection: np.ndarray,
    component_inverse: np.ndarray,
    *,
    sample_uniforms=None,
    sample_state_uniforms=None,
) -> dict[str, np.ndarray]:
    total = BURN + TRAINING + OOS
    anchor = np.asarray(calibrated["anchor"], dtype=float)
    scale_kappa = np.asarray(calibrated["scale_kappa"], dtype=float)
    eta_kappa = np.asarray(calibrated["eta_kappa"], dtype=float)
    even_kappa = np.asarray(calibrated["even_kappa"], dtype=float)
    use_eta = dgp == "m3_eta_plus_m4_even"
    use_even = dgp in ("m4_endpoint_even", "m3_eta_plus_m4_even")

    values = np.empty((total, MASTER_N))
    uniforms = np.empty_like(values)
    reference_states = np.empty((total, 4))
    q_states = np.empty((total, helmert.shape[1]))
    scale_scores = np.zeros((22, 1))
    eta_scores = np.zeros((22, 1))
    q_scores = np.zeros((22, helmert.shape[1]))
    eta_state = float(anchor[2])
    log_variance = float(anchor[1])
    q_state = np.zeros(helmert.shape[1])

    for t in range(total):
        state = anchor.copy()
        state[1] = log_variance
        state[2] = eta_state
        reference_states[t] = state
        q_states[t] = q_state
        sampler = sample_u if sample_uniforms is None else sample_uniforms
        if sample_state_uniforms is None:
            u = sampler(MASTER_N, q_state, masses, helmert, component_inverse, rng)
        else:
            u = sample_state_uniforms(
                MASTER_N, q_state, masses, helmert, component_inverse, rng,
                reference_state=state,
            )
        z = core.hansen_ppf(u, state[2:])
        x = np.exp(0.5 * log_variance) * z
        uniforms[t], values[t] = u, x

        _log_density, observation_scores = core.reference_logpdf_and_score(x, state)
        daily_reference_score = observation_scores.mean(axis=0)
        scale_scores = np.vstack((scale_scores, [[daily_reference_score[1]]]))[-22:]

        efficient_shape = (
            daily_reference_score[2:]
            - shape_geometry.projection_shape_on_ms @ daily_reference_score[:2]
        )
        eta_scores = np.vstack((eta_scores, [[efficient_shape[0]]]))[-22:]

        phi = core.normalized_bspline_basis(u, knots, core.DEGREE, masses)
        logits = np.log(masses) + helmert @ q_state
        weights = np.exp(logits - logsumexp(logits))
        fitted = phi @ weights
        responsibilities = phi * weights[None, :] / fitted[:, None]
        raw_q = helmert.T @ (responsibilities.mean(axis=0) - weights)
        efficient_q = raw_q - q_projection @ daily_reference_score[:2]
        scalar_even = float(directions[0] @ efficient_q)
        even_component = directions[0] * scalar_even
        q_scores = np.vstack((q_scores, even_component[None, :]))[-22:]

        log_variance = float(anchor[1])
        eta_state = float(anchor[2])
        q_state = np.zeros(helmert.shape[1])
        scale_average = score_averages(scale_scores)
        eta_average = score_averages(eta_scores)
        q_average = score_averages(q_scores)
        for h in range(3):
            log_variance += scale_kappa[h] * float(scale_average[h][0])
            if use_eta:
                eta_state += eta_kappa[h] * float(eta_average[h][0])
            if use_even:
                q_state += even_kappa[h] * q_average[h]
        if not (-6.0 < log_variance < 6.0):
            raise FloatingPointError(f"unstable DGP log variance: {log_variance}")
        if not (-20.0 < eta_state < 20.0):
            raise FloatingPointError(f"unstable DGP eta state: {eta_state}")
        if np.max(np.abs(q_state)) > 100.0:
            raise FloatingPointError("unstable DGP q state")

    keep = slice(BURN, None)
    even_denominator = float(directions[0] @ directions[0])
    return {
        "values": values[keep],
        "uniforms": uniforms[keep],
        "reference_states": reference_states[keep],
        "q_states": q_states[keep],
        "eta_state": reference_states[keep, 2],
        "even_state": q_states[keep] @ directions[0] / even_denominator,
    }


def flatten_panel(values: np.ndarray, n: int) -> tuple[np.ndarray, np.ndarray]:
    selected = np.asarray(values[:, :n], dtype=float)
    return selected.ravel(), np.arange(0, (len(selected) + 1) * n, n, dtype=int)


def reference_filter_from_states(
    values: np.ndarray, offsets: np.ndarray, states: np.ndarray,
) -> core.FourStateFilter:
    days = len(offsets) - 1
    scores = np.empty((days, 4))
    contributions = np.empty(days)
    for t, (start, stop) in enumerate(zip(offsets[:-1], offsets[1:])):
        log_density, observation_score = core.reference_logpdf_and_score(
            values[start:stop], states[t]
        )
        scores[t] = observation_score.mean(axis=0)
        contributions[t] = log_density.mean()
    return core.FourStateFilter(
        states=states.copy(), means=states[:, 0].copy(),
        log_variances=states[:, 1].copy(), variances=np.exp(states[:, 1]),
        eta=np.array([core.state_to_parameters(row[2:])[0] for row in states]),
        skew=np.array([core.state_to_parameters(row[2:])[1] for row in states]),
        scores=scores, contributions=contributions,
        terminal_state=states[-1].copy(), terminal_score_history=scores[-22:].copy(),
    )


def optimize_scaled(objective, starts: list[np.ndarray], dimension: int):
    fits = [
        minimize(
            objective, np.asarray(start, dtype=float), method="L-BFGS-B",
            bounds=[(-1000.0, 1000.0)] * dimension,
            options={"maxiter": 1000, "ftol": 1e-11, "gtol": 1e-7,
                     "eps": 1e-5, "maxls": 50},
        )
        for start in starts
    ]
    finite = [fit for fit in fits if np.isfinite(float(fit.fun))]
    if not finite:
        raise RuntimeError("all simulation optimization starts failed")
    return min(finite, key=lambda fit: float(fit.fun)), fits


@dataclass(frozen=True)
class ScalarEtaFilter:
    states: np.ndarray
    scores: np.ndarray
    efficient_eta_scores: np.ndarray
    contributions: np.ndarray
    gradient: np.ndarray | None
    parameter_scores: np.ndarray | None = None

    @property
    def composite_log_likelihood(self) -> float:
        return float(self.contributions.sum())


@dataclass(frozen=True)
class ScalarEndpointFilter:
    states: np.ndarray
    scalar_states: np.ndarray
    driver_scores: np.ndarray
    contributions: np.ndarray
    weights: np.ndarray
    gradient: np.ndarray | None
    parameter_scores: np.ndarray | None = None

    @property
    def composite_log_likelihood(self) -> float:
        return float(self.contributions.sum())


def filter_eta_scalar(
    values: np.ndarray,
    offsets: np.ndarray,
    frozen: core.FourStateFilter,
    anchor: np.ndarray,
    geometry: shape.ShapeGeometry,
    kappas: np.ndarray,
    *,
    gradient: bool = False,
) -> ScalarEtaFilter:
    """Eta-only staged filter with an exact recursive parameter gradient."""
    kappas = np.asarray(kappas, dtype=float)
    days = len(offsets) - 1
    eta = float(anchor[2])
    eta_derivative = np.zeros(3)
    history = np.zeros(22)
    derivative_history = np.zeros((22, 3))
    states = frozen.states.copy()
    scores = np.empty((days, 4))
    efficient_scores = np.empty(days)
    contributions = np.empty(days)
    total_gradient = np.zeros(3) if gradient else None
    parameter_scores = np.empty((days, 3)) if gradient else None
    step = 1e-4
    for t, (start, stop) in enumerate(zip(offsets[:-1], offsets[1:])):
        state = frozen.states[t].copy()
        state[2:] = (eta, anchor[3])
        log_density, observation_score = core.reference_logpdf_and_score(
            values[start:stop], state
        )
        daily_score = observation_score.mean(axis=0)
        efficient = float(
            daily_score[2]
            - geometry.projection_shape_on_ms[0] @ daily_score[:2]
        )
        states[t] = state
        scores[t] = daily_score
        efficient_scores[t] = efficient
        contributions[t] = float(log_density.mean())
        if gradient:
            assert total_gradient is not None
            parameter_scores[t] = daily_score[2] * eta_derivative
            total_gradient += parameter_scores[t]
            derivatives = []
            for sign in (1.0, -1.0):
                shifted = state.copy()
                shifted[2] += sign * step
                _log, shifted_score = core.reference_logpdf_and_score(
                    values[start:stop], shifted
                )
                shifted_daily = shifted_score.mean(axis=0)
                derivatives.append(float(
                    shifted_daily[2]
                    - geometry.projection_shape_on_ms[0] @ shifted_daily[:2]
                ))
            score_state_derivative = (derivatives[0] - derivatives[1]) / (2 * step)
            efficient_derivative = score_state_derivative * eta_derivative
        else:
            efficient_derivative = np.zeros(3)
        history = np.r_[history[1:], efficient]
        derivative_history = np.vstack((derivative_history[1:], efficient_derivative))
        eta = float(anchor[2])
        eta_derivative = np.zeros(3)
        for h, window in enumerate(core.WINDOWS):
            average = float(history[-window:].sum() / window)
            eta += kappas[h] * average
            if gradient:
                eta_derivative[h] += average
                eta_derivative += kappas[h] * derivative_history[-window:].sum(axis=0) / window
        if not np.isfinite(eta) or abs(eta) > 20.0:
            raise FloatingPointError("unstable scalar eta filter")
    return ScalarEtaFilter(
        states=states, scores=scores, efficient_eta_scores=efficient_scores,
        contributions=contributions, gradient=total_gradient,
        parameter_scores=parameter_scores,
    )


def fit_eta_scalar(
    values: np.ndarray, offsets: np.ndarray, frozen: core.FourStateFilter,
    anchor: np.ndarray, geometry: shape.ShapeGeometry, n: int,
    empirical_start: np.ndarray,
) -> tuple[np.ndarray, ScalarEtaFilter, dict[str, float]]:
    null = filter_eta_scalar(values, offsets, frozen, anchor, geometry, np.zeros(3))
    averages = fixed_denominator_score_averages(
        null.efficient_eta_scores[:, None], core.WINDOWS
    )
    units = np.array([
        1e-2 / max(float(np.median(np.abs(avg[:, 0]))), 1e-10)
        for avg in averages
    ])

    def run(theta, with_gradient=False):
        return filter_eta_scalar(
            values, offsets, frozen, anchor, geometry,
            np.asarray(theta) * units, gradient=with_gradient,
        )

    kappas, filtered, diagnostics = maximize_scalar_filter(run, units, len(offsets) - 1)
    if not diagnostics["success"]:
        raise RuntimeError(f"eta optimizer did not converge: {diagnostics}")
    lr = max(0.0, 2.0 * n * (filtered.composite_log_likelihood - null.composite_log_likelihood))
    diagnostics.update(lr=lr, p=float(chi2.sf(lr, 3)) if diagnostics["success"] else float("nan"))
    return kappas, filtered, diagnostics


def endpoint_cluster(
    scalar_state: float, phi: np.ndarray, masses: np.ndarray,
    helmert: np.ndarray, direction: np.ndarray,
) -> tuple[float, float, float, np.ndarray, np.ndarray]:
    q_state = direction * scalar_state
    logits = np.log(masses) + helmert @ q_state
    weights = np.exp(logits - logsumexp(logits))
    fitted = np.maximum(phi @ weights, 1e-300)
    responsibilities = phi * weights[None, :] / fitted[:, None]
    mean_responsibility = responsibilities.mean(axis=0)
    raw_q = helmert.T @ (mean_responsibility - weights)
    raw_scalar = float(direction @ raw_q)
    mean_covariance = (
        np.diag(mean_responsibility)
        - responsibilities.T @ responsibilities / len(phi)
    )
    weight_covariance = np.diag(weights) - np.outer(weights, weights)
    hessian_q = helmert.T @ (mean_covariance - weight_covariance) @ helmert
    scalar_hessian = float(direction @ hessian_q @ direction)
    return float(np.log(fitted).mean()), raw_scalar, scalar_hessian, weights, q_state


def filter_endpoint_scalar(
    phi: np.ndarray,
    offsets: np.ndarray,
    reference_scores: np.ndarray,
    masses: np.ndarray,
    helmert: np.ndarray,
    direction: np.ndarray,
    projection: np.ndarray,
    kappas: np.ndarray,
    *,
    gradient: bool = False,
) -> ScalarEndpointFilter:
    days = len(offsets) - 1
    scalar_state = 0.0
    state_derivative = np.zeros(3)
    history = np.zeros(22)
    derivative_history = np.zeros((22, 3))
    states = np.empty((days, helmert.shape[1]))
    scalar_states = np.empty(days)
    driver_scores = np.empty(days)
    contributions = np.empty(days)
    weights_path = np.empty((days, len(masses)))
    total_gradient = np.zeros(3) if gradient else None
    parameter_scores = np.empty((days, 3)) if gradient else None
    for t, (start, stop) in enumerate(zip(offsets[:-1], offsets[1:])):
        contribution, raw_scalar, scalar_hessian, weights, q_state = endpoint_cluster(
            scalar_state, phi[start:stop], masses, helmert, direction
        )
        projection_scalar = float(direction @ projection @ reference_scores[t, :2])
        driver = raw_scalar - projection_scalar
        states[t], scalar_states[t] = q_state, scalar_state
        driver_scores[t], contributions[t], weights_path[t] = driver, contribution, weights
        if gradient:
            assert total_gradient is not None
            parameter_scores[t] = raw_scalar * state_derivative
            total_gradient += parameter_scores[t]
            driver_derivative = scalar_hessian * state_derivative
        else:
            driver_derivative = np.zeros(3)
        history = np.r_[history[1:], driver]
        derivative_history = np.vstack((derivative_history[1:], driver_derivative))
        scalar_state = 0.0
        state_derivative = np.zeros(3)
        for h, window in enumerate(core.WINDOWS):
            average = float(history[-window:].sum() / window)
            scalar_state += kappas[h] * average
            if gradient:
                state_derivative[h] += average
                state_derivative += kappas[h] * derivative_history[-window:].sum(axis=0) / window
        if not np.isfinite(scalar_state) or abs(scalar_state) > 100.0:
            raise FloatingPointError("unstable scalar endpoint filter")
    return ScalarEndpointFilter(
        states=states, scalar_states=scalar_states,
        driver_scores=driver_scores, contributions=contributions,
        weights=weights_path, gradient=total_gradient,
        parameter_scores=parameter_scores,
    )


def fit_endpoint_scalar(
    phi: np.ndarray, offsets: np.ndarray, reference_scores: np.ndarray,
    masses: np.ndarray, helmert: np.ndarray, direction: np.ndarray,
    projection: np.ndarray, n: int, empirical_start: np.ndarray,
) -> tuple[np.ndarray, ScalarEndpointFilter, dict[str, float]]:
    null = filter_endpoint_scalar(
        phi, offsets, reference_scores, masses, helmert, direction,
        projection, np.zeros(3),
    )
    averages = fixed_denominator_score_averages(
        null.driver_scores[:, None], core.WINDOWS
    )
    direction_norm = float(np.linalg.norm(direction))
    units = np.array([
        1e-2 / max(float(np.median(np.abs(avg[:, 0]))) * direction_norm, 1e-10)
        for avg in averages
    ])

    def run(theta, with_gradient=False):
        return filter_endpoint_scalar(
            phi, offsets, reference_scores, masses, helmert, direction,
            projection, np.asarray(theta) * units, gradient=with_gradient,
        )

    kappas, filtered, diagnostics = maximize_scalar_filter(run, units, len(offsets) - 1)
    if not diagnostics["success"]:
        raise RuntimeError(f"endpoint optimizer did not converge: {diagnostics}")
    lr = max(0.0, 2.0 * n * (filtered.composite_log_likelihood - null.composite_log_likelihood))
    diagnostics.update(lr=lr, p=float(chi2.sf(lr, 3)) if diagnostics["success"] else float("nan"))
    return kappas, filtered, diagnostics


def correction_quantile(
    alpha: float,
    weights: np.ndarray,
    grid: np.ndarray,
    component_cdf: np.ndarray,
) -> float:
    cdf = np.maximum.accumulate(component_cdf @ weights)
    cdf[0], cdf[-1] = 0.0, 1.0
    return float(np.interp(alpha, cdf, grid))


def model_oos_scores(
    values_matrix: np.ndarray,
    reference: core.FourStateFilter,
    correction: ScalarEndpointFilter | None,
    anchor: np.ndarray,
    masses: np.ndarray,
    helmert: np.ndarray,
    grid: np.ndarray,
    component_cdf: np.ndarray,
) -> dict[str, float]:
    start = TRAINING
    log_values, q_losses = [], {alpha: [] for alpha in TAIL_LEVELS}
    for t in range(start, start + OOS):
        state = reference.states[t]
        observations = values_matrix[t]
        log_density, _score = core.reference_logpdf_and_score(observations, state)
        if correction is None:
            weights = masses
            log_correction = np.zeros(len(observations))
        else:
            weights = correction.weights[t]
            u = core.dynamic_reference_pit(
                observations,
                np.array([0, len(observations)]),
                state[None, :],
            )
            phi = core.normalized_bspline_basis(
                u, core.make_clamped_knots(base.BREAKPOINTS, core.DEGREE),
                core.DEGREE, masses,
            )
            log_correction = np.log(np.maximum(phi @ weights, 1e-300))
        log_values.append(float(np.mean(log_density + log_correction)))
        for alpha in TAIL_LEVELS:
            u_alpha = (
                alpha if correction is None
                else correction_quantile(alpha, weights, grid, component_cdf)
            )
            z_alpha = float(core.hansen_ppf(np.array([u_alpha]), state[2:])[0])
            quantile = float(state[0] + np.exp(0.5 * state[1]) * z_alpha)
            residual = observations - quantile
            q_losses[alpha].append(float(np.mean(
                residual * (alpha - (residual < 0.0).astype(float))
            )))
    return {
        "log_score": float(np.mean(log_values)),
        **{f"q_loss_{alpha:g}": float(np.mean(q_losses[alpha]))
           for alpha in TAIL_LEVELS},
    }


def correlation_rmse(estimate: np.ndarray, truth: np.ndarray) -> tuple[float, float]:
    estimate = np.asarray(estimate[TRAINING:], dtype=float)
    truth = np.asarray(truth[TRAINING:], dtype=float)
    rmse = float(np.sqrt(np.mean((estimate - truth) ** 2)))
    if np.std(estimate) <= 1e-12 or np.std(truth) <= 1e-12:
        return float("nan"), rmse
    return float(np.corrcoef(estimate, truth)[0, 1]), rmse


def one_replication(
    replication: int, *, sample_uniforms=None, fit_inference=None,
    sample_sizes=None, dgps=None, sample_state_uniforms=None,
) -> list[dict[str, object]]:
    rng = np.random.default_rng(SEED + replication)
    calibrated = calibration()
    anchor = np.asarray(calibrated["anchor"])
    knots = core.make_clamped_knots(base.BREAKPOINTS, core.DEGREE)
    masses = core.bspline_masses(knots, core.DEGREE)
    helmert = core.helmert_submatrix(len(masses))
    directions = np.vstack(endpoint.endpoint_directions(helmert))
    shape_geometry = shape.shape_geometry(anchor)
    q_geometry = scoring.corrected_tangent_geometry(
        anchor, masses, knots, masses, helmert, (0, 1),
        "simulation q score projected off known location/log variance",
    )
    grid, _basis, component_cdf, component_inverse = prepare_component_sampler(
        knots, masses
    )
    saved = json.loads(CALIBRATION.read_text(encoding="utf-8"))
    empirical_m3 = np.asarray(saved["model3_betas"], dtype=float)[:, 0]
    empirical_m4 = np.asarray(saved["model4"]["coefficients"], dtype=float)[0]
    empirical_m5 = np.asarray(saved["model5"]["coefficients"], dtype=float)[0]
    rows: list[dict[str, object]] = []

    for dgp in (DGP_NAMES if dgps is None else dgps):
        master = generate_master_panel(
            dgp, rng, calibrated, knots, masses, helmert, directions,
            shape_geometry, q_geometry.projection_q_on_hansen,
            component_inverse,
            sample_uniforms=sample_uniforms,
            sample_state_uniforms=sample_state_uniforms,
        )
        for n in (SAMPLE_SIZES if sample_sizes is None else sample_sizes):
            matrix = master["values"][:, :n]
            values, offsets = flatten_panel(master["values"], n)
            m2_states = master["reference_states"].copy()
            m2_states[:, 2:] = anchor[2:]
            m2 = reference_filter_from_states(values, offsets, m2_states)
            train_stop = TRAINING * n
            train_offsets = offsets[: TRAINING + 1]

            m3_betas, _m3_train, m3_test = fit_eta_scalar(
                values[:train_stop], train_offsets, reference_filter_from_states(
                    values[:train_stop], train_offsets, m2_states[:TRAINING]
                ), anchor, shape_geometry, n, empirical_m3,
            )
            m3_full = filter_eta_scalar(
                values, offsets, m2, anchor, shape_geometry, m3_betas
            )
            m3_reference = reference_filter_from_states(
                values, offsets, m3_full.states
            )

            m2_u = core.dynamic_reference_pit(values, offsets, m2.states)
            m2_phi = core.normalized_bspline_basis(
                m2_u, knots, core.DEGREE, masses
            )
            m4_coefficients, _m4_train, m4_test = fit_endpoint_scalar(
                m2_phi[:train_stop], train_offsets, m2.scores[:TRAINING],
                masses, helmert, directions[0], q_geometry.projection_q_on_hansen,
                n, empirical_m4,
            )
            m4_full = filter_endpoint_scalar(
                m2_phi, offsets, m2.scores, masses, helmert, directions[0],
                q_geometry.projection_q_on_hansen, m4_coefficients,
            )

            m3_u = core.dynamic_reference_pit(values, offsets, m3_full.states)
            m3_phi = core.normalized_bspline_basis(
                m3_u, knots, core.DEGREE, masses
            )
            m5_coefficients, _m5_train, m5_test = fit_endpoint_scalar(
                m3_phi[:train_stop], train_offsets, m3_full.scores[:TRAINING],
                masses, helmert, directions[0], q_geometry.projection_q_on_hansen,
                n, empirical_m5,
            )
            m5_full = filter_endpoint_scalar(
                m3_phi, offsets, m3_full.scores, masses, helmert, directions[0],
                q_geometry.projection_q_on_hansen, m5_coefficients,
            )

            scores = {
                "M2": model_oos_scores(
                    matrix, m2, None, anchor, masses, helmert, grid, component_cdf
                ),
                "M3": model_oos_scores(
                    matrix, m3_reference, None, anchor, masses, helmert,
                    grid, component_cdf,
                ),
                "M4": model_oos_scores(
                    matrix, m2, m4_full, anchor, masses, helmert,
                    grid, component_cdf,
                ),
                "M5": model_oos_scores(
                    matrix, m3_reference, m5_full, anchor, masses, helmert,
                    grid, component_cdf,
                ),
            }
            true_eta = master["eta_state"]
            true_even = master["even_state"]
            eta_corr, eta_rmse = correlation_rmse(m3_full.states[:, 2], true_eta)
            m4_even = m4_full.scalar_states
            m5_even = m5_full.scalar_states
            m4_corr, m4_rmse = correlation_rmse(m4_even, true_even)
            m5_corr, m5_rmse = correlation_rmse(m5_even, true_even)
            row: dict[str, object] = {
                "replication": replication, "dgp": dgp, "N": n,
                "m3_lr": m3_test["lr"], "m3_lr_p": m3_test["p"],
                "m4_lr": m4_test["lr"], "m4_lr_p": m4_test["p"],
                "m5_lr": m5_test["lr"], "m5_lr_p": m5_test["p"],
                "m3_optimizer_success": m3_test["success"],
                "m4_optimizer_success": m4_test["success"],
                "m5_optimizer_success": m5_test["success"],
                "m3_eta_state_correlation": eta_corr,
                "m3_eta_state_rmse": eta_rmse,
                "m4_even_state_correlation": m4_corr,
                "m4_even_state_rmse": m4_rmse,
                "m5_even_state_correlation": m5_corr,
                "m5_even_state_rmse": m5_rmse,
            }
            for model, diagnostics, coefficients, state_path in (
                ("m3", m3_test, m3_betas, m3_full.states[:, 2]),
                ("m4", m4_test, m4_coefficients, m4_full.scalar_states),
                ("m5", m5_test, m5_coefficients, m5_full.scalar_states),
            ):
                for key, value in diagnostics.items():
                    if key not in ("lr", "p", "success"):
                        row[f"{model}_optimizer_{key}"] = value
                for h, coefficient in zip(core.WINDOWS, coefficients):
                    row[f"{model}_coefficient_h{h}"] = float(coefficient)
                row[f"{model}_estimated_state_std_oos"] = float(np.std(state_path[TRAINING:]))
            if fit_inference is not None:
                m2_training = reference_filter_from_states(
                    values[:train_stop], train_offsets, m2_states[:TRAINING]
                )
                inference_filters = (
                    ("m3", m3_betas, lambda k: filter_eta_scalar(
                        values[:train_stop], train_offsets, m2_training,
                        anchor, shape_geometry, k, gradient=True,
                    )),
                    ("m4", m4_coefficients, lambda k: filter_endpoint_scalar(
                        m2_phi[:train_stop], train_offsets, m2.scores[:TRAINING],
                        masses, helmert, directions[0],
                        q_geometry.projection_q_on_hansen, k, gradient=True,
                    )),
                    ("m5", m5_coefficients, lambda k: filter_endpoint_scalar(
                        m3_phi[:train_stop], train_offsets, m3_full.scores[:TRAINING],
                        masses, helmert, directions[0],
                        q_geometry.projection_q_on_hansen, k, gradient=True,
                    )),
                )
                for model, coefficients, run_filter in inference_filters:
                    for key, value in fit_inference(coefficients, run_filter).items():
                        row[f"{model}_{key}"] = value
                    if row[f"{model}_optimizer_at_boundary"]:
                        row[f"{model}_wald_valid"] = False
                        row[f"{model}_wald_p"] = float("nan")
            for model, model_scores in scores.items():
                for metric, value in model_scores.items():
                    row[f"{model}_{metric}"] = value
            rows.append(row)
            p_label = "LR" if fit_inference is None else "Wald"
            p_values = (
                (m3_test["p"], m4_test["p"], m5_test["p"])
                if fit_inference is None
                else tuple(row[f"{m}_wald_p"] for m in ("m3", "m4", "m5"))
            )
            print(
                f"rep={replication} dgp={dgp} N={n} "
                f"{p_label} p(M3/M4/M5)={p_values[0]:.3g}/{p_values[1]:.3g}/{p_values[2]:.3g}",
                flush=True,
            )
    return rows


def summarize(frame: pd.DataFrame) -> dict[str, object]:
    rows = []
    for (dgp, n), block in frame.groupby(["dgp", "N"], sort=False):
        row: dict[str, object] = {
            "dgp": dgp, "N": int(n), "replications": len(block),
        }
        for model in ("m3", "m4", "m5"):
            row[f"{model}_lr_rejection_rate_5pct"] = float(
                np.mean(block[f"{model}_lr_p"] < 0.05)
            )
        for column in (
            "m3_eta_state_correlation", "m3_eta_state_rmse",
            "m4_even_state_correlation", "m4_even_state_rmse",
            "m5_even_state_correlation", "m5_even_state_rmse",
        ):
            row[f"mean_{column}"] = float(block[column].mean())
        for model in ("M2", "M3", "M4", "M5"):
            row[f"mean_{model}_log_score"] = float(block[f"{model}_log_score"].mean())
            for alpha in TAIL_LEVELS:
                column = f"{model}_q_loss_{alpha:g}"
                row[f"mean_{column}"] = float(block[column].mean())
        for proposed, benchmark in (("M3", "M2"), ("M4", "M2"), ("M5", "M3"), ("M5", "M4")):
            row[f"log_gain_{proposed}_vs_{benchmark}"] = float(
                np.mean(block[f"{proposed}_log_score"] - block[f"{benchmark}_log_score"])
            )
            for alpha in TAIL_LEVELS:
                row[f"q{alpha:g}_gain_{proposed}_vs_{benchmark}"] = float(np.mean(
                    block[f"{benchmark}_q_loss_{alpha:g}"]
                    - block[f"{proposed}_q_loss_{alpha:g}"]
                ))
        rows.append(row)
    summary_frame = pd.DataFrame(rows)
    summary_frame.to_csv(OUTPUT / "summary.csv", index=False)
    calibrated = calibration()
    json_records = summary_frame.replace({np.nan: None}).to_dict(orient="records")
    result = {
        "design": {
            "master_N": MASTER_N, "sample_sizes": list(SAMPLE_SIZES),
            "training_days": TRAINING, "oos_days": OOS, "burn_in": BURN,
            "replications": int(frame.replication.nunique()),
            "dgps": list(DGP_NAMES),
            "nested_samples": True,
            "known_in_estimation": "static skew-t anchor and true location/scale path",
            "inference": "three-parameter full-likelihood LR for each active scalar direction; daily cross sections conditionally iid in DGP",
            "coefficient_calibration": "S&P 500 final Case1 coefficients times sqrt(100/491)",
            "adjustment": float(calibrated["adjustment"]),
            "scale_kappa": np.asarray(calibrated["scale_kappa"]).tolist(),
            "eta_kappa": np.asarray(calibrated["eta_kappa"]).tolist(),
            "even_kappa": np.asarray(calibrated["even_kappa"]).tolist(),
        },
        "summary": json_records,
    }
    (OUTPUT / "summary.json").write_text(
        json.dumps(result, indent=2, allow_nan=False) + "\n", encoding="utf-8"
    )
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--replications", type=int, default=REPLICATIONS)
    parser.add_argument("--start", type=int, default=0)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--summarize-only", action="store_true")
    args = parser.parse_args()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    if args.summarize_only:
        frame = pd.read_csv(OUTPUT / "replications.csv")
        print(json.dumps(summarize(frame), indent=2), flush=True)
        return
    if args.replications < 1 or args.workers < 1:
        raise ValueError("replications and workers must be positive")
    replications = list(range(args.start, args.start + args.replications))
    path = OUTPUT / f"replications_{replications[0]}_{replications[-1]}.csv"
    rows: list[dict[str, object]] = []
    workers = min(args.workers, args.replications)
    if workers == 1:
        for replication in replications:
            rows.extend(one_replication(replication))
            pd.DataFrame(rows).to_csv(path, index=False)
    else:
        with ProcessPoolExecutor(max_workers=workers) as executor:
            futures = {executor.submit(one_replication, r): r for r in replications}
            for completed, future in enumerate(as_completed(futures), 1):
                rows.extend(future.result())
                pd.DataFrame(rows).sort_values(["replication", "dgp", "N"]).to_csv(
                    path, index=False
                )
                print(f"completed replication {completed}/{len(replications)}", flush=True)
    paths = sorted(OUTPUT.glob("replications_*.csv"))
    combined = pd.concat((pd.read_csv(p) for p in paths), ignore_index=True)
    combined = combined.drop_duplicates(["replication", "dgp", "N"], keep="last")
    combined = combined.sort_values(["replication", "dgp", "N"])
    combined.to_csv(OUTPUT / "replications.csv", index=False)
    print(json.dumps(summarize(combined), indent=2), flush=True)


if __name__ == "__main__":
    main()
