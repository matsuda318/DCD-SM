"""Targeted cross-sectional-information simulation for DCD-SM.

A master panel of N*=100 observations drives one common score-driven density
path.  Nested panels N={1,20,50,100} observe that same path, so changing N
changes filtering information but not the true conditional distribution.

The location/scale path is generated by the empirical S&P 500 M2 scale
recursion and is treated as known in estimation.  Three shape DGPs are used:

* M2:       no shape dynamics;
* M4-only:  endpoint-even dynamics, with eta/lambda fixed;
* M3+M4:    eta and endpoint-even dynamics.

For every observed N, M3, M4 and staged M5 are re-estimated on the training
sample.  The code reports likelihood-ratio detection, state recovery and
strict-OOS log/Q-loss performance.  The experiment is intentionally favorable
to shape filtering because the static reference and location/scale path are
known.  It therefore isolates the information loss caused by small N.
"""

